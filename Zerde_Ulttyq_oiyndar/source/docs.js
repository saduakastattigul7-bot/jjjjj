const runs = (t, o = {}) => String(t).split(/(\*\*[^*]+\*\*)/).filter(Boolean).flatMap(seg => {
  const b = seg.startsWith("**"); if (b) seg = seg.slice(2, -2);
  return seg.split(HL).filter(p => p !== "").map(p => new TextRun({
    text: p, font: F, size: o.size || S, bold: o.bold || b, italics: o.italics,
    highlight: HL.test(p) || o.hl ? "yellow" : undefined,
  }));
});
