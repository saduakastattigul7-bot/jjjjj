function table(TW, pct, header, rows, o = {}) {
  const w = pct.map(p => Math.floor(TW * p / 100));
  w[w.length - 1] += TW - w.reduce((a, c) => a + c, 0);
  const cell = (t, i, head) => new TableCell({
    borders, width: { size: w[i], type: WidthType.DXA }, verticalAlign: VerticalAlign.CENTER,
    shading: head ? { fill: "E7EEF5", type: ShadingType.CLEAR, color: "auto" } : undefined,
    margins: { top: 40, bottom: 40, left: 80, right: 80 },
    children: String(t).split("\n").map(line => new Paragraph({ alignment: head || o.center?.includes(i) ? C : L,
      spacing: { line: 240 }, children: runs(line, { size: o.size || ST, bold: head }) })),
  });
  return new Table({
    width: { size: TW, type: WidthType.DXA }, columnWidths: w,
    rows: [new TableRow({ tableHeader: true, children: header.map((h, i) => cell(h, i, true)) }),
      ...rows.map(r => new TableRow({ cantSplit: true, children: r.map((c, i) => cell(c, i, false)) }))],
  });
}
