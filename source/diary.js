function table(pct, header, rows, o = {}) {
  const w = pct.map(p => Math.floor(TW * p / 100));
  w[w.length - 1] += TW - w.reduce((a, c) => a + c, 0);
  const cell = (t, i, head) => new TableCell({
    borders, width: { size: w[i], type: WidthType.DXA }, verticalAlign: VerticalAlign.CENTER,
    shading: head ? { fill: "E7EEF5", type: ShadingType.CLEAR, color: "auto" } : undefined,
    margins: { top: 40, bottom: 40, left: 80, right: 80 },
    children: [new Paragraph({ alignment: head || o.center?.includes(i) ? C : AlignmentType.LEFT,
      spacing: { line: 240 }, children: runs(t, { size: ST, bold: head }) })],
  });
  return new Table({
    width: { size: TW, type: WidthType.DXA }, columnWidths: w,
    rows: [
      new TableRow({ tableHeader: true, children: header.map((h, i) => cell(h, i, true)) }),
      ...rows.map(r => new TableRow({ cantSplit: true, height: o.minH ? { value: o.minH, rule: "atLeast" } : undefined,
        children: r.map((c, i) => cell(c, i, false)) })),
    ],
  });
}
