function save(name, children, landscape = false) {
  const page = landscape
    ? { size: { ...A4, orientation: PageOrientation.LANDSCAPE }, margin: { top: 1134, bottom: 1134, left: 1134, right: 1134 } }
    : { size: A4, margin: { top: 1134, bottom: 1134, left: 1701, right: 1134 } };
  const doc = new Document({ creator: "", title: name, styles: { default: { document: { run: { font: F, size: S } } } },
    sections: [{ properties: { page }, footers: { default: footer }, children }] });
  return Packer.toBuffer(doc).then(buf => { fs.writeFileSync(path.join(OUT, name + ".docx"), buf); console.log("written", name); });
}
