const HL_RE = /(⟦[^⟧]*⟧)/;

const runs = (t, o = {}) => t.split(HL_RE).filter(Boolean).map(p => {
  const hl = HL_RE.test(p);
  return new TextRun({ text: hl ? "[" + p.slice(1, -1) + "]" : p, font: FONT, size: o.size || SZ,
    bold: o.bold, italics: o.italics, highlight: hl ? "yellow" : undefined });
});
const P = (t, o = {}) => new Paragraph({
  alignment: o.align ?? J, indent: o.ind ? { firstLine: Math.round(1.25 * CM) } : undefined,
  spacing: { line: o.line || 276, before: o.before || 0, after: o.after ?? 60 }, children: runs(t, o),
});
