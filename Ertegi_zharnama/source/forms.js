function table(textW, widthsPct, header, rows, o = {}) {
  const widths = widthsPct.map(p => Math.floor(textW * p / 100));
  widths[widths.length - 1] += textW - widths.reduce((a, b) => a + b, 0);
  const mk = (t, w, head, i) => new TableCell({
    borders, width: { size: w, type: WidthType.DXA }, verticalAlign: VerticalAlign.CENTER,
    shading: head ? { fill: "E7EEF5", type: ShadingType.CLEAR, color: "auto" } : undefined,
    margins: { top: 40, bottom: 40, left: 80, right: 80 },
    children: String(t).split("\n").map(line => new Paragraph({
      alignment: head || (o.center || []).includes(i) ? C : L, spacing: { line: 240 },
      children: runs(line, { size: o.size || SZ_T, bold: head || (o.bold0 && i === 0) }),
    })),
  });
  const trs = [];
  if (header) trs.push(new TableRow({ tableHeader: true, children: header.map((h, i) => mk(h, widths[i], true, i)) }));
  rows.forEach(r => trs.push(new TableRow({ cantSplit: true, children: r.map((c, i) => mk(c, widths[i], false, i)) })));
  return new Table({ width: { size: textW, type: WidthType.DXA }, columnWidths: widths, rows: trs });
}
